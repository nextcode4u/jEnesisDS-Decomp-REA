"""Generate the Z80 opcode dispatch pages from the named handler index."""
import argparse
import csv
from itertools import groupby
from pathlib import Path
import re

OUTPUT_NAME = "z80_dispatch.c"
OPCODE_INDEX = Path(__file__).resolve().parents[1] / "decompiled/arm9/functions.tsv"
PAGE_SIZE = 256
PAGES = (
    ("alternate", "alternate", 0x020153F0, 48),
    ("base", "base", 0x020154B0, PAGE_SIZE),
    ("CB", "cb", 0x020158B0, PAGE_SIZE),
    ("ED", "ed", 0x02015CB0, PAGE_SIZE),
    ("DD/FD", "index", 0x020160B0, PAGE_SIZE),
    ("DD/FD CB", "indexed_cb", 0x020164B0, PAGE_SIZE),
)
OPCODE = re.compile(r"(DD/FD CB|DD/FD|base|CB|ED|alternate) 0x([0-9A-F]{2}) \(")
DEFAULT_HANDLERS = {
    "ED": "z80_ed_undefined_ed_02010f00",
    "DD/FD": "resume_base_decode_after_unused_index_prefix",
}


def dispatch_pages():
    aliases = {prefix: {} for prefix, _, _, _ in PAGES}
    addresses = {}
    with OPCODE_INDEX.open(encoding="utf-8", newline="") as table:
        for row in csv.DictReader(table, delimiter="\t"):
            if row["subsystem"] != "z80":
                continue
            symbol = row["symbol"]
            addresses[symbol] = int(row["address"], 16)
            for prefix, code in OPCODE.findall(row["description"]):
                opcode = int(code, 16)
                if opcode in aliases[prefix]:
                    raise ValueError(f"Duplicate Z80 {prefix} slot {opcode:#04x}")
                aliases[prefix][opcode] = symbol

    slots = {}
    for prefix, name, _, count in PAGES:
        slots[name] = [
            select_handler(prefix, opcode, aliases[prefix]) for opcode in range(count)
        ]
    used = set().union(*slots.values())
    return slots, {symbol: addresses[symbol] for symbol in sorted(used)}


def select_handler(prefix, opcode, aliases):
    # The analysis index abbreviates long alias lists. Fill those from the
    # release's decoding rules before applying the page's default handler.
    if prefix == "ED":
        if opcode & 0xc7 == 0x44:  # NEG duplicates throughout the 0x40 group.
            opcode = 0x44
        elif opcode == 0x7d:  # The last duplicate RETN slot.
            opcode = 0x45
    elif prefix == "DD/FD" and opcode == 0xcb:
        return "dispatch_indexed_cb_with_displacement"
    elif prefix == "DD/FD CB" and opcode & 0xc0 == 0x40:
        opcode &= 0xf8  # Indexed BIT ignores the register operand.
    elif prefix == "alternate" and opcode & 0x08:
        opcode &= 0xf8  # Each group aliases its last eight slots.
    if opcode in aliases:
        return aliases[opcode]
    if prefix in DEFAULT_HANDLERS:
        return DEFAULT_HANDLERS[prefix]
    raise ValueError(f"Missing Z80 {prefix} slot {opcode:#04x}")


def write_source(output):
    slots, addresses = dispatch_pages()
    with output.open("w", encoding="ascii", newline="\n") as source:
        source.write("/* Generated by generate_z80_dispatch.py. */\n")
        source.write("typedef void (*Z80OpcodeEntry)(void);\n\n")
        for symbol in addresses:
            source.write(f"extern void {symbol}(void);\n")
        for _, name, _, count in PAGES:
            source.write(
                f"\nconst Z80OpcodeEntry z80_{name}_dispatch[{count}]\n"
                f'    __attribute__((section(".rodata.z80_{name}"))) = {{\n'
            )
            first = 0
            for symbol, group in groupby(slots[name]):
                last = first + sum(1 for _ in group) - 1
                indices = f"{first:#04x}" if first == last else f"{first:#04x} ... {last:#04x}"
                source.write(f"    [{indices}] = {symbol},\n")
                first = last + 1
            source.write("};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    write_source(parser.parse_args().output)
