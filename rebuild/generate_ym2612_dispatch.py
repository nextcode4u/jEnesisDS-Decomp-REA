"""Generate the ARM7 YM2612 algorithm and active-operator dispatch table."""
import argparse
import csv
from pathlib import Path
import re

OUTPUT_NAME = "arm7_ym2612_dispatch.c"
OPCODE_INDEX = Path(__file__).resolve().parents[1] / "decompiled/arm7/functions.tsv"
HANDLER = re.compile(r"ym2612_(?:render|silence)_algorithm_([0-7])_mask_([0-9a-f]{2})")


def read_handlers():
    handlers = {}
    with OPCODE_INDEX.open(encoding="utf-8", newline="") as table:
        for row in csv.DictReader(table, delimiter="\t"):
            match = HANDLER.fullmatch(row["role"])
            if match is None:
                continue
            algorithm, mask = int(match[1]), int(match[2], 16)
            key = (algorithm, mask)
            if mask >= 16 or key in handlers:
                raise ValueError(f"Unexpected YM2612 dispatch entry {row['role']}")
            handlers[key] = (row["symbol"], int(row["address"], 16))
    if len(handlers) != 8 * 16:
        raise ValueError("Expected a YM2612 handler for each algorithm and operator mask")
    return handlers


def write_source(output):
    handlers = read_handlers()
    with output.open("w", encoding="ascii", newline="\n") as source:
        source.write("/* Generated by generate_ym2612_dispatch.py. */\n")
        source.write("typedef void (*Ym2612SampleLoop)(void);\n\n")
        for symbol, _ in handlers.values():
            source.write(f"extern void {symbol}(void);\n")
        source.write("\ntypedef struct {\n"
                     "    Ym2612SampleLoop modes[8][16];\n"
                     "    const Ym2612SampleLoop *base;\n"
                     "} Ym2612Dispatch;\n")
        source.write("\nconst Ym2612Dispatch ym2612_dispatch = {\n    .modes = {\n")
        for algorithm in range(8):
            source.write(f"        [{algorithm}] = {{\n")
            for active_mask in range(16):
                symbol, _ = handlers[algorithm, active_mask]
                source.write(f"            [{active_mask:#04x}] = {symbol},\n")
            source.write("        },\n")
        source.write("    },\n    .base = &ym2612_dispatch.modes[0][0],\n};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    write_source(parser.parse_args().output)
