"""Generate the Genesis VDP counter and DS scanline mapping tables."""
import argparse
from pathlib import Path

OUTPUT_NAME = "vdp_timing_tables.c"
HORIZONTAL_TABLE_LENGTH = 488
HALF_CPU_CYCLES_PER_LINE = 975

TABLES = (
    ("vdp_vertical_counter", 0x0208E5E0, 320),
    ("vdp_horizontal_counter_h32", 0x0208E720, HORIZONTAL_TABLE_LENGTH),
    ("vdp_horizontal_counter_h40", 0x0208E908, HORIZONTAL_TABLE_LENGTH),
    ("ds_sprite_height_lines_removed", 0x0208EAF0, 192),
    ("ds_line_from_genesis_scanline", 0x0208EBB0, 224),
)


def horizontal_counter(steps_per_line, first_skipped, resume):
    for cycle in range(HORIZONTAL_TABLE_LENGTH):
        counter = cycle * 2 * steps_per_line // HALF_CPU_CYCLES_PER_LINE
        yield counter + (resume - first_skipped if counter >= first_skipped else 0)


def vertical_counter():
    for line in range(320):
        # The NTSC counter jumps from 0xea to 0xe5 and stops at 0xff.
        yield min(0xff, line - (6 if line > 0xea else 0))


def ds_line_from_genesis_scanline():
    for line in range(224):
        groups, within_group = divmod(line, 7)
        # Scaling 224 to 192 drops the seventh line of each group. The
        # renderer uses 200 as the marker and falls back to the previous line.
        yield 200 if within_group == 6 else groups * 6 + within_group


def write_source(output):
    values_by_table = (
        vertical_counter(),
        horizontal_counter(171, 0x94, 0xe9),
        horizontal_counter(211, 0xb7, 0xe4),
        (height // 6 for height in range(192)),
        ds_line_from_genesis_scanline(),
    )
    with output.open("w", encoding="ascii", newline="\n") as source:
        source.write("/* Generated by generate_vdp_timing_tables.py. */\n#include <stdint.h>\n")
        for (name, _, size), values in zip(TABLES, values_by_table):
            values = list(values)
            if len(values) != size:
                raise ValueError(f"Expected {size} entries for {name}")
            source.write(f'\nconst uint8_t {name}[{size}]\n'
                         f'    __attribute__((section(".rodata.{name}"))) = {{\n')
            for index in range(0, size, 16):
                row = ", ".join(f"{value:#04x}" for value in values[index:index + 16])
                source.write(f"    {row},\n")
            source.write("};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    write_source(parser.parse_args().output)
